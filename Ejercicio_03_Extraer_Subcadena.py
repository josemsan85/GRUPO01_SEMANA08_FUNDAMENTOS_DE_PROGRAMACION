# Ejercicio 3 - EXTRAER SUBCADENA (usando slicing)
texto = "Análisis de Datos con Python"

# Posiciones: "Datos" empieza en 12 y termina antes de la 17
palabra1 = texto[12:17]

# "Python" empieza en 22 y llega hasta el final
palabra2 = texto[22:]

print(f"Palabra 1: {palabra1}")
print(f"Palabra 2: {palabra2}")
